/**
 * 利用者の経験レベル。その人にとって「何が見えていないか」で分け、問いの種類と画面の構成をこれに合わせる。
 * ここでの理解は「部品の役割と、そのつながりを自分で再構成できること」。レベルが変わっても、この定義は変わらない。
 * - beginner: 基本。コードそのものが見えていない。処理を追える(何を受け取り、何を返し、次にどこが呼ばれるか)ことを確かめる
 * - intermediate: 実務。部品どうしのつながりが見えていない。変更がどこに及ぶかを予想できることを確かめる
 * - advanced: 上級。エージェントの判断が見えていない。変更を受け入れてよいか(何が確かめられていないか)を自分で判断する
 */
export type LearnerLevel = 'beginner' | 'intermediate' | 'advanced';

export const LEARNER_LEVELS: LearnerLevel[] = ['beginner', 'intermediate', 'advanced'];

export const LEVEL_LABEL: Record<LearnerLevel, string> = {
  beginner: 'コードを追う',
  intermediate: '影響を予想する',
  advanced: '変更を判断する',
};

export const LEVEL_DESCRIPTION: Record<LearnerLevel, string> = {
  beginner: 'コードを1行ずつ追いたい人向け。1画面に問いは1つ。具体的な値や、目の前の行で確かめます。',
  intermediate: '実務エンジニア向け。変更がどこに及ぶかを予想しながら、ステップをたどります。',
  advanced: 'レビューする人向け。問いは判断の分かれ目だけ。変えなかった場所をそのままにしてよいかを、自分で判断します。',
};

/**
 * レベルごとの画面の構成。言葉づかいだけでなく、問いの数・形・見せる情報をここで変える。
 * 文章の量を抑えるため、どのレベルでも、答える前に見せるのは「目的1行 + コード + 問い」だけにする。
 */
export interface LevelProfile {
  /** 1つのコードに置く空欄の上限 */
  maxBlanks: number;
  /** 選択肢の数 (このコードになるものを含む) */
  optionCount: number;
  /** 問いにするステップの上限 (それ以外のステップは、差分と1行の理由で見せる) */
  maxQuizSteps: number;
  /** 仕組みの質問で、問いにする範囲の上限 */
  maxReadItems: number;
  /** 受け入れ条件を見せるか */
  criteria: boolean;
  /**
   * 変更の影響の問いの形。
   * - lines: 実際の行を見せて、変える必要がある行を選ぶ
   * - places: 変更が必要になる場所を、候補の場所から選ぶ
   * - review: エージェントが変えなかった場所の扱いが妥当かを判断する (正誤は付けず、気になった場所として最後に残す)
   */
  impact: 'lines' | 'places' | 'review';
  /** review で判断を求める場所の上限 (依頼全体で) */
  maxReviews: number;
  /** 計算で確かめられるときは、コードの代わりに具体的な値で問う */
  values: boolean;
  /** 1画面に問いは1つ: 前の問いに答えてから、次の問いを出す */
  oneAtATime: boolean;
  /** 問いの無いステップは、止まらずに続けて見せる */
  flow: boolean;
  /** まとめ (仕組みの説明の空欄) に置く空欄の上限 */
  recapBlanks: number;
}

const PROFILES: Record<LearnerLevel, LevelProfile> = {
  beginner: { maxBlanks: 1, optionCount: 3, maxQuizSteps: 3, maxReadItems: 2, criteria: false, impact: 'lines', maxReviews: 0, values: true, oneAtATime: true, flow: false, recapBlanks: 1 },
  intermediate: { maxBlanks: 2, optionCount: 4, maxQuizSteps: 4, maxReadItems: 3, criteria: true, impact: 'places', maxReviews: 0, values: false, oneAtATime: false, flow: false, recapBlanks: 2 },
  advanced: { maxBlanks: 2, optionCount: 4, maxQuizSteps: 2, maxReadItems: 2, criteria: true, impact: 'review', maxReviews: 3, values: false, oneAtATime: false, flow: true, recapBlanks: 3 },
};

export function levelProfile(level: LearnerLevel): LevelProfile {
  return PROFILES[level];
}

export function coerceLevel(value: unknown): LearnerLevel {
  return LEARNER_LEVELS.includes(value as LearnerLevel) ? (value as LearnerLevel) : 'intermediate';
}

/**
 * 利用者に見せる文章の言葉づかい(全プロンプト共通)。
 * 画面は「プロのエンジニアが要件からどう考えて変更するか」をたどる形にしているので、試験・勉強のための言葉は使わせない
 * (日々の開発でコードの理解を深めるための道具であり、学習用の教材ではないため)。
 */
export const WORDING_RULE =
  '利用者に見せる文章(目標・課題・手がかり・解説・理由など)では「問題」「クイズ」「出題」「正解」「不正解」「空欄」「穴埋め」「採点」「解答」「ヒント」「〜問」といった試験のような言葉や、' +
  '「学習」「学習者」「学ぶ」「復習」「教材」といった勉強のための言葉を使わない。利用者に呼びかけるときは「あなた」とする。' +
  'エンジニアが要件からコードを読み、考え、変更する過程として書く(例: 「この空欄には」→「ここに入るコードは」、「正解は」→「このコードになるのは」、「この問題では」→「この変更では」「このコードでは」)。';

/**
 * 利用者が主体であること(全プロンプト共通)。
 * システムが作業を済ませたという報告ではなく、利用者がこれから自分の判断で実装していく手順として書かせる。
 */
export const VOICE_RULE =
  '文章は、利用者がこれから自分の判断で実装していく手順として書く。「実装しました」「変更しました」「調整しました」「追加済みです」「対応しておきました」のような、' +
  '作業を済ませたという報告の形は使わない。「〜するために、〜を〜に変える」「〜する必要がある」「〜を追加する」のように、これから行うこととその理由を述べる。' +
  'コードについて確かめた事実は「〜になっている」「〜から呼ばれている」と現在形で述べる。';

/**
 * 前提を知らなくても読めること(基本・実務のレベル)。
 * 利用者は調査の経緯を見ていないので、その言葉だけでは分からない表現には説明を補わせる。
 */
export const CONTEXT_RULE =
  '利用者は、調査の経緯もここまでのやり取りも見ていない。その言葉だけでは何を指すか分からない表現' +
  '(このプロジェクト固有の関数名・型名・変数名・ファイル名・略語・独自の用語、「先ほどの処理」「この仕組み」「上記の変更」のように前提を要する言い方)は、' +
  '最初に出るところで、それが何で、どこにあり、何をするものかを短く補う(例: 「cartTotal(カートの合計金額を計算する関数。src/cart.ts)」)。指示語だけで済ませない。';

/** その文章が、作業を済ませたという報告の形になっているか */
export function soundsLikeReport(text: string): boolean {
  return /(ました|済みです|済みになっています|してあります|完了です)/.test(text ?? '');
}

/** 出題プロンプトに入れる、レベル別の指針 */
export function levelGuide(level: LearnerLevel): string {
  const common = [
    '【利用者に見せる文章の言葉づかい(全レベル共通)】',
    `- ${WORDING_RULE}`,
    `- ${VOICE_RULE}`,
    ...(level === 'advanced' ? [] : [`- ${CONTEXT_RULE}`]),
    '【解説の飛躍を避ける(全レベル共通)】',
    '- 結論だけを書かない。「根拠の行(ファイル名:行) → そこで何が起きるか → だからこのコードになる」の順に、途中の段階を省かない。',
    '- 参照コードに無い仕組み・ライブラリの内部動作を推測で語らない。分からないことは書かない。',
    '- 1つの文で新しい概念を2つ以上持ち込まない。',
    '【文章の量(全レベル共通)】',
    '- 利用者が読む量を抑える。同じことを別の項目で言い直さない。コードを見れば分かること(追加した引数の名前など)を文章で繰り返さない。',
  ];
  const byLevel: Record<LearnerLevel, string[]> = {
    beginner: [
      '【利用者のレベル: 基本(プログラミングの基本から確かめる人)】',
      '- 対象: プログラミングの基本(変数・条件分岐・繰り返し・関数・引数と戻り値)を確かめながらコードを読む人。',
      '- 専門用語は避け、使うときは初出で短く言い換える(例: 「非同期処理(終わるのを待たずに次へ進む処理)」「コールバック(あとで呼んでもらう関数)」)。英字の略語は使わないか、必ず説明する。',
      '- 空欄は item あたり1個だけ。呼び出す関数・渡す値・戻り値の式・条件式など、目の前の行だけで考えられるものにする。高度な構文(ジェネリクス、デコレータ、複雑な型、正規表現)は空欄にしない。',
      '- 誤答は、基本を確かめている人が実際にしがちな誤り(変数の取り違え、条件の反転、引数の入れ違い、呼ぶ関数の取り違え)。違いが1か所で、画面に見えているコードの名前だけを使う。',
      '- 実装問題は小さな変更(数行)にし、新しい名前は必ず newNames で示す。',
      '- ヒントは具体的に。hintApproach では「どの行の何という名前を見ればよいか」まで言う(答えは書かない)。',
      '- 解説(why/explanation)は短い文で、「何を受け取り → 何をして → 何を返すか(次にどこが呼ばれるか)」の順に。',
      '- read は「この関数は何を受け取り、何を返すか」「この条件が真になるのはいつか」といった基本の読み取りを中心にする。',
    ],
    intermediate: [
      '【利用者のレベル: 実務エンジニア】',
      '- 対象: 基本的な文法や一般的な技術(非同期処理、型、クラス、HTTP、イベント、依存性の注入など)は分かっていて、実際のシステム開発に使っている人。',
      '- 一般的な技術用語は説明なしで使ってよい。このプロジェクト固有の仕組み・命名・約束事は、根拠の行を示して説明する。',
      '- 空欄は item あたり1〜2個。ほかの部品とのつながりが表れる箇所(どの関数を呼ぶか、何を渡すか、結果をどこへ返すか)を選ぶ。',
      '- 誤答は実務でありがちな誤り(似た名前の別メソッド、責務の違う層の関数、エラー時の扱いの違い、境界値の違い)。呼び出し先の定義や呼び出し元を読めば判断できるものにする。',
      '- 解説では「なぜこの設計か」(責務の分け方、データの流れ、エラー処理、他の書き方との違い)を、具体的なファイル名・関数名で説明する。',
      '- 実装問題は、既存の手本に沿って機能を足す・直す変更を中心にする。',
    ],
    advanced: [
      '【利用者のレベル: 上級(高度・複雑なシステムの開発者)】',
      '- 対象: 一般的な技術は使いこなしていて、このコードベース独自の仕組みや、一般的でない技術・設計を確実に理解したい人。',
      '- 一般的な用語や基本構文の説明は不要。その代わり、独自の仕組み・不変条件(常に守られるべき約束)・境界条件・並行性・性能・設計上のトレードオフに焦点を当てる。',
      '- 空欄は item あたり1〜2個。誤ると影響の大きい判断の分かれ目(独自APIの使い方、不変条件を守る条件式、順序が重要な処理、エッジケースの扱い)だけを選ぶ。',
      '- そのような分かれ目が無い変更・範囲には item を作らない(見れば分かる箇所を空欄にしない)。',
      '- 誤答は、一見正しく動きそうだが設計上の約束を破るもの(順序の入れ替え、不変条件の確認漏れ、並行時に壊れる書き方、独自APIの似た別メソッド)。根拠の行を読み込まないと判断できないものにする。',
      '- 解説は簡潔に要点を述べるが、独自の仕組みについては根拠の行と因果関係を省略しない。',
      '- 実装問題は、既存の設計方針や不変条件を壊さずに拡張する変更を中心にする。',
    ],
  };
  return [...byLevel[level], '', ...common].join('\n');
}

/** 答え漏れの書き直しなど、短い文章を書かせるときの文体指示 */
export function levelStyle(level: LearnerLevel): string {
  return (
    {
      beginner: '読み手はプログラミングの基本から確かめている人です。専門用語は避けるか、短く言い換えてください。',
      intermediate: '読み手は実務エンジニアです。一般的な技術用語はそのまま使って構いません。',
      advanced: '読み手は上級者です。簡潔に、要点だけを書いてください。',
    }[level] +
    WORDING_RULE +
    VOICE_RULE +
    (level === 'advanced' ? '' : CONTEXT_RULE)
  );
}
